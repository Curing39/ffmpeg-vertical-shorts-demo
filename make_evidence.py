"""Portfolio image: source frame + crop and fill outputs side by side, all read from the real files."""
from __future__ import annotations

import subprocess
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

from shorts import default_font

HERE = Path(__file__).parent
EVID = HERE / "evidence"
FONT = default_font()


def grab(path: Path, t: float) -> Image.Image:
    tmp = EVID / "_tmp.png"
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-ss", f"{t:.3f}", "-i", str(path), "-frames:v", "1", str(tmp)],
                   check=True)
    img = Image.open(tmp).convert("RGB")
    img.load()
    tmp.unlink()
    return img


def main() -> None:
    EVID.mkdir(exist_ok=True)
    t_clip = 2.0  # 2 s into clip02 (source 33 s), inside a caption
    src = grab(HERE / "sample" / "source_16x9.mp4", 31.0 + t_clip).resize((960, 540))
    crop = grab(HERE / "out" / "crop" / "clip02.mp4", t_clip).resize((405, 720))
    fill = grab(HERE / "out" / "fill" / "clip02.mp4", t_clip).resize((405, 720))
    W, H = 960 + 405 * 2 + 4 * 40, 720 + 170
    canvas = Image.new("RGB", (W, H), (7, 8, 13))
    d = ImageDraw.Draw(canvas)
    big, small = ImageFont.truetype(FONT, 34), ImageFont.truetype(FONT, 22)
    d.text((40, 30), "16:9 source -> vertical 1080x1920 clips (crop / fill), captions retimed and burned in",
           font=big, fill=(244, 246, 252))
    y0 = 110
    canvas.paste(src, (40, y0 + 90))
    canvas.paste(crop, (40 + 960 + 40, y0))
    canvas.paste(fill, (40 + 960 + 40 + 405 + 40, y0))
    d.text((40, y0 + 90 + 550), "Source (synthetic, generated by ffmpeg)", font=small, fill=(150, 158, 178))
    d.text((1040, y0 + 730), "--framing crop --offset 0.5", font=small, fill=(150, 158, 178))
    d.text((1485, y0 + 730), "--framing fill", font=small, fill=(150, 158, 178))
    d.text((40, H - 45), "Independent demo, synthetic footage. Same frame (2.0 s into clip02) in all three panels.",
           font=small, fill=(150, 158, 178))
    canvas.save(EVID / "crop_vs_fill.png", optimize=True)
    for mode in ("fill", "crop"):
        Image.open(HERE / "out" / mode / "clip01_contact.jpg").save(EVID / f"contact_sheet_{mode}_clip01.jpg")
    print("wrote", sorted(p.name for p in EVID.iterdir()))


if __name__ == "__main__":
    main()
